/**
 * MCP 密钥的三个上限 —— **前后端共用同一份定义**。
 *
 * 这个模块**不 import 任何东西**（现在连类型都不需要）：前端组件（`'use client'`）
 * 也要 import 它，所以不能碰 `db.ts` / `better-sqlite3` / Node 内置。
 * 往这里加东西之前先问一句：客户端打包进来会不会炸。
 *
 * ── 三个量、三种约束，别混 ──────────────────────────────────────────────
 *
 *  · `MAX_NOTE_LENGTH` —— **产品约束**：备注能写多长。按**字素簇**（用户眼里的
 *    「字符」）算，`😀` 算 1、`🧑‍🚀` 算 1、汉字算 1。
 *  · `MAX_BODY_BYTES`  —— **传输约束**：一次请求最多能塞多少 **UTF-8 字节**。
 *  · `MAX_KEYS`        —— **数量约束**：最多能同时存在几把密钥。
 *
 * **前两个独立，谁也保证不了谁。** 一个「字符」里可以有任意多个组合记号
 * （Unicode 的 `Extend*`，例如 `a` 后面跟 64 个 U+0301），所以 64 个字素簇
 * **可以**远远超过 8192 字节。实测（task-50）：
 *
 *   · 64 个簇、每簇 1 个字母 + 48 个组合记号 → 请求体 6219 字节 → 后端 201
 *   · 64 个簇、每簇 1 个字母 + 64 个组合记号 → 请求体 8267 字节 → 后端 **400「请求体过大」**
 *
 * 前端如果**只查字素簇**，就会出现「UI 显示 64/64、按钮可用」→ 提交 → 后端拒绝 ——
 * 一句用户看得见的谎。**前端三个都要查**（数量那个也要：到 20 把就该先禁用「生成」，
 * 而不是让用户点完再吃一个 400）；后端三个都查，而且后端是最终判定。
 *
 * ── 还有一条别忘 ──────────────────────────────────────────────────────
 * 字素簇的切分**不保证跨引擎一致**（Node 与 Chromium 对 `Extended_Pictographic`
 * 的判定不同）。详见 `src/lib/mcp-key.ts` 里 `graphemeLength` 的注释。
 * 所以前端按字素簇算出来的「64 个字符」只是**提示**，不是承诺。
 */

/** 备注长度上限：**字素簇**个数，不是码元数、不是字节数（见模块注释） */
export const MAX_NOTE_LENGTH = 64;

/** 请求体大小上限：**UTF-8 字节**，8 KiB（见模块注释） */
export const MAX_BODY_BYTES = 8192;

/** 密钥数量上限：够用，且让 listMcpKeys / verifyMcpKey 的规模可控（见模块注释） */
export const MAX_KEYS = 20;

